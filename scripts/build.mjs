/**
 * Build `client.js` from `src/client/entry.jsx`.
 *
 * DSH serves one classic script per plugin; its module loader runs the wrapper
 * factory lazily and provides `react` from the shell's frozen module table.
 * Everything else is bundled, so the artifact is self-contained apart from
 * React and the host's theme.
 *
 * Usage:
 *   node scripts/build.mjs           write client.js
 *   node scripts/build.mjs --check   compare client.js with a fresh build
 *
 * esbuild is a development dependency. When the plugin is built from a
 * checkout without `node_modules`, set `NODE_PATH` to a directory containing
 * esbuild.
 */

import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT = resolve(ROOT, 'client.js')
const ENTRY = resolve(ROOT, 'src/client/entry.jsx')

/** Wrap an esbuild CommonJS bundle in DSH's module-loader envelope. */
function envelope(code) {
  return `/**
 * Browser half of dsh-vcs-panel. Generated by scripts/build.mjs from src/client/;
 * do not edit by hand. React is provided by the host module table.
 */
window.__ModuleLoader__.load({
  id: 'dsh-vcs-panel',
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  },
});
`
}

const { build } = require('esbuild')
const result = await build({
  entryPoints: [ENTRY],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  jsx: 'automatic',
  external: ['react', 'react/jsx-runtime'],
  loader: { '.css': 'text' },
  minify: true,
  legalComments: 'none',
  logLevel: 'warning',
})

const code = result.outputFiles[0].text
const output = envelope(code)
const check = process.argv.includes('--check')

if (check) {
  const current = readFileSync(OUTPUT, 'utf8')
  if (current !== output) {
    console.error('client.js is stale; run `node scripts/build.mjs`.')
    process.exitCode = 1
  } else {
    console.log('client.js is up to date.')
  }
} else {
  writeFileSync(OUTPUT, output)
  console.log(`wrote client.js (${(output.length / 1024).toFixed(1)} KiB)`)
}
